// Minimal reactive i18n: English source strings are the keys, Russian is
// the only translation. Missing keys fall back to the key itself.
import { language } from './language.svelte'

function resolveLang(): 'en' | 'ru' {
  const v = language.value
  if (v === 'ru') return 'ru'
  if (v === 'en') return 'en'
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ru')) return 'ru'
  return 'en'
}

