export function t(key: string): string {
  if (resolveLang() === 'ru') return ru[key] ?? key
  return key
}

// Count + noun with Russian plural forms (1 результат, 3 результата, 5 результатов).
export function n(count: number, enOne: string, enMany: string, ruOne: string, ruFew: string, ruMany: string): string {
  if (resolveLang() === 'ru') {
    const m10 = count % 10
    const m100 = count % 100
    const form = (m10 === 1 && m100 !== 11) ? ruOne
      : ([2, 3, 4].includes(m10) && ![12, 13, 14].includes(m100)) ? ruFew : ruMany
    return `${count} ${form}`
  }
  return `${count} ${count === 1 ? enOne : enMany}`
}
